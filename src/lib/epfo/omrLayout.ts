/**
 * Geometry of the printable EPFO OMR sheet (A4, millimetres). The PDF writer and
 * the photo reader share these numbers, so a printed sheet can be read back.
 */
import type { EpfoPaper } from "./types";

export const OMR_PAGE = { w: 210, h: 297 };
export const MARKER = { size: 9 };
/** Top-left corners of the four solid registration squares. */
export const MARKER_TL: [number, number][] = [
  [10, 10],
  [191, 10],
  [10, 278],
  [191, 278],
];
export const MARKER_CENTERS: [number, number][] = MARKER_TL.map(([x, y]) => [x + MARKER.size / 2, y + MARKER.size / 2]);

/** Solid bar printed only at the top-left — tells the reader which way is up. */
export const ORIENT_BAR = { x: 24, y: 12.5, w: 40, h: 4 };

export const GRID = {
  top: 82,
  rows: 30,
  pitch: 6.3,
  blocks: [21, 65, 109, 153],
  bubbleDx: 13,
  bubbleGap: 7.5,
  r: 2.3,
};

export function bubbleCenter(qIndex: number, opt: number): [number, number] {
  const block = Math.floor(qIndex / GRID.rows);
  const row = qIndex % GRID.rows;
  const x0 = GRID.blocks[block]!;
  return [x0 + GRID.bubbleDx + opt * GRID.bubbleGap, GRID.top + row * GRID.pitch];
}

export interface Painter {
  rect(x: number, y: number, w: number, h: number, fill: boolean, gray?: number, lw?: number): void;
  circle(x: number, y: number, r: number, fill: boolean, gray?: number, lw?: number): void;
  line(x1: number, y1: number, x2: number, y2: number, gray?: number, lw?: number): void;
  text(s: string, x: number, y: number, size: number, opts?: { bold?: boolean; align?: "left" | "center" | "right"; gray?: number }): void;
}

/** Draws the full OMR sheet. gray: 0 = black, 1 = white. */
export function drawOmr(p: Painter, paper: Pick<EpfoPaper, "id" | "title">, questionCount = 120) {
  for (const [x, y] of MARKER_TL) p.rect(x, y, MARKER.size, MARKER.size, true, 0);
  p.rect(ORIENT_BAR.x, ORIENT_BAR.y, ORIENT_BAR.w, ORIENT_BAR.h, true, 0);

  p.text("mockGE  ·  EPFO APFC MOCK TEST", 105, 16.5, 12, { bold: true, align: "center" });
  p.text("OMR ANSWER SHEET", 105, 23, 10, { bold: true, align: "center", gray: 0.2 });
  p.text(`${paper.title}   |   Paper code: ${paper.id.toUpperCase()}`, 105, 29, 8.5, { align: "center", gray: 0.25 });

  // candidate details
  p.rect(21, 33, 168, 22, false, 0.4, 0.3);
  p.text("Candidate's name", 24, 38, 7.5, { gray: 0.3 });
  p.line(50, 38.5, 130, 38.5, 0.6, 0.2);
  p.text("Roll No.", 134, 38, 7.5, { gray: 0.3 });
  for (let i = 0; i < 8; i++) p.rect(147 + i * 5, 34.5, 5, 5, false, 0.5, 0.2);
  p.text("Date", 24, 46, 7.5, { gray: 0.3 });
  p.line(32, 46.5, 70, 46.5, 0.6, 0.2);
  p.text("Test booklet series:", 76, 46, 7.5, { gray: 0.3 });
  ["A", "B", "C", "D"].forEach((s, i) => {
    p.circle(106 + i * 7, 45, 2, false, 0.35, 0.25);
    p.text(s, 106 + i * 7, 46.1, 6, { align: "center", gray: 0.55 });
  });
  p.text("Signature", 140, 46, 7.5, { gray: 0.3 });
  p.line(155, 46.5, 186, 46.5, 0.6, 0.2);
  p.text("Time: 2 hours   ·   120 questions   ·   2.5 marks each   ·   one-third negative marking", 105, 52.5, 7, { align: "center", gray: 0.3 });

  // instructions
  p.text("HOW TO MARK", 21, 61, 7.5, { bold: true });
  p.text("Use a black or blue ball-point pen. Darken ONE bubble completely for each question.", 21, 65.5, 7, { gray: 0.25 });
  p.text("Correct:", 21, 70, 7, { gray: 0.25 });
  p.circle(35, 69, 2, true, 0);
  p.text("Wrong:", 45, 70, 7, { gray: 0.25 });
  p.circle(56, 69, 2, false, 0.35, 0.25);
  p.line(54.6, 67.6, 57.4, 70.4, 0, 0.35);
  p.line(57.4, 67.6, 54.6, 70.4, 0, 0.35);
  p.circle(63, 69, 2, false, 0.35, 0.25);
  p.line(61.8, 69.2, 62.7, 70.2, 0, 0.35);
  p.line(62.7, 70.2, 64.4, 67.8, 0, 0.35);
  p.circle(70, 69, 2, false, 0.35, 0.25);
  p.circle(70, 69, 0.6, true, 0);
  p.text("Multiple marks = wrong answer. Keep the four black corner squares visible when you photograph the sheet.", 76, 70, 6.5, { gray: 0.25 });

  // grid headers
  for (const x0 of GRID.blocks) {
    p.text("Q.No.", x0 + 6.5, GRID.top - 6.2, 6, { bold: true, align: "right", gray: 0.3 });
    ["a", "b", "c", "d"].forEach((l, j) => p.text(l, x0 + GRID.bubbleDx + j * GRID.bubbleGap, GRID.top - 6.2, 6.5, { bold: true, align: "center", gray: 0.3 }));
  }

  for (let q = 0; q < questionCount; q++) {
    const [bx, by] = bubbleCenter(q, 0);
    const x0 = bx - GRID.bubbleDx;
    if (q % 5 === 0 && q % GRID.rows !== 0) p.line(x0, by - GRID.pitch / 2, x0 + 40, by - GRID.pitch / 2, 0.75, 0.15);
    p.text(String(q + 1), x0 + 6.5, by + 1.1, 7, { bold: true, align: "right", gray: 0.15 });
    for (let j = 0; j < 4; j++) {
      const [cx, cy] = bubbleCenter(q, j);
      p.circle(cx, cy, GRID.r, false, 0.35, 0.25);
      p.text("abcd"[j]!, cx, cy + 0.9, 5.5, { align: "center", gray: 0.6 });
    }
  }
  p.text("Do not fold or staple this sheet. Generated by mockGE for self-assessment.", 105, 292, 6.5, { align: "center", gray: 0.45 });
}

/** Canvas painter (mm → px) used for previews and self-tests. */
export function canvasPainter(ctx: CanvasRenderingContext2D, pxPerMm: number): Painter {
  const g = (v = 0) => {
    const c = Math.round(v * 255);
    return `rgb(${c},${c},${c})`;
  };
  return {
    rect(x, y, w, h, fill, gray = 0, lw = 0.3) {
      if (fill) {
        ctx.fillStyle = g(gray);
        ctx.fillRect(x * pxPerMm, y * pxPerMm, w * pxPerMm, h * pxPerMm);
      } else {
        ctx.strokeStyle = g(gray);
        ctx.lineWidth = lw * pxPerMm;
        ctx.strokeRect(x * pxPerMm, y * pxPerMm, w * pxPerMm, h * pxPerMm);
      }
    },
    circle(x, y, r, fill, gray = 0, lw = 0.3) {
      ctx.beginPath();
      ctx.arc(x * pxPerMm, y * pxPerMm, r * pxPerMm, 0, Math.PI * 2);
      if (fill) {
        ctx.fillStyle = g(gray);
        ctx.fill();
      } else {
        ctx.strokeStyle = g(gray);
        ctx.lineWidth = lw * pxPerMm;
        ctx.stroke();
      }
    },
    line(x1, y1, x2, y2, gray = 0, lw = 0.3) {
      ctx.beginPath();
      ctx.moveTo(x1 * pxPerMm, y1 * pxPerMm);
      ctx.lineTo(x2 * pxPerMm, y2 * pxPerMm);
      ctx.strokeStyle = g(gray);
      ctx.lineWidth = lw * pxPerMm;
      ctx.stroke();
    },
    text(s, x, y, size, opts = {}) {
      ctx.fillStyle = g(opts.gray ?? 0);
      ctx.font = `${opts.bold ? "bold " : ""}${(size * 0.3528 * pxPerMm).toFixed(2)}px Helvetica, Arial, sans-serif`;
      ctx.textAlign = opts.align ?? "left";
      ctx.textBaseline = "alphabetic";
      ctx.fillText(s, x * pxPerMm, y * pxPerMm);
    },
  };
}
